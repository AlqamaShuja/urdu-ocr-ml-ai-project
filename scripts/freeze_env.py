"""Write requirements-lock.txt with the exact versions currently installed.

Run after a successful `scripts/check_env.py`:

    python scripts/freeze_env.py

requirements.txt holds loose, human-edited ranges; requirements-lock.txt holds
the resolved versions actually used for the experiments. Both are committed, so
a run can be reproduced later.
"""

from __future__ import annotations

import platform
import subprocess
import sys
from datetime import date
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
LOCK_FILE = PROJECT_ROOT / "requirements-lock.txt"


def main() -> int:
    frozen = subprocess.run(
        [sys.executable, "-m", "pip", "freeze"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout

    header = (
        "# Resolved local environment. Generated by scripts/freeze_env.py -- do not edit by hand.\n"
        f"# Date generated : {date.today().isoformat()}\n"
        f"# Python         : {platform.python_version()} ({platform.platform()})\n"
        "# Scope          : local Windows CPU environment only. Colab pins live elsewhere.\n"
        "#\n"
        "# Note: a torch line with a '+cpu' local version tag must be reinstalled from\n"
        "# https://download.pytorch.org/whl/cpu , not from plain PyPI.\n"
        "\n"
    )

    LOCK_FILE.write_text(header + frozen, encoding="utf-8")
    package_count = sum(1 for line in frozen.splitlines() if line.strip() and not line.startswith("#"))
    print(f"Wrote {LOCK_FILE} ({package_count} packages).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
